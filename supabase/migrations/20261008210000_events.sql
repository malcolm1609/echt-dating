-- Treffen auf dem Server (Regeln wie src/domain/events.ts): kleine Events im eigenen Gebiet, Plätze je zur
-- Hälfte für Frauen und Männer, Gruppenchat für alle, die dabei sind, nach dem Event Sterne und
-- „Wen möchtest du wiedersehen?“; nur gegenseitige Wünsche werden zu Matches.
-- Die App liest über my_events() und schreibt nur über die Funktionen unten.
-- Noch nicht auf dem Server: Echt Plus (früher anmelden, Rabatt), Campus-Bestätigung, Nicht-Erscheinen.

create table events (
  id bigint generated by default as identity primary key,
  host_id uuid not null references profiles on delete cascade,
  area_id bigint not null references areas,
  title text not null check (length(trim(title)) between 3 and 80),
  kind text not null check (kind in ('Feiern', 'Essen & Trinken', 'Sport', 'Spiele', 'Kultur', 'Draußen')),
  place text not null check (length(trim(place)) between 1 and 120),
  when_text text not null,
  starts_at timestamptz not null,
  seats int not null,
  price numeric(5, 2) not null default 0 check (price between 0 and 50),
  access text not null default 'open' check (access in ('open', 'invite')),
  campus text,
  tonight boolean not null default false,
  created_at timestamptz not null default now(),
  check (case when tonight then seats in (4, 6, 8) and price = 0 else seats in (8, 10, 12) end)
);
create index events_area on events (area_id, starts_at);

create table event_attendees (
  event_id bigint not null references events on delete cascade,
  user_id uuid not null references profiles on delete cascade,
  gender text not null check (gender in ('f', 'm')),
  joined_at timestamptz not null default now(),
  primary key (event_id, user_id)
);

create table event_invites (
  event_id bigint not null references events on delete cascade,
  user_id uuid not null references profiles on delete cascade,
  primary key (event_id, user_id)
);

create table event_messages (
  id bigint generated by default as identity primary key,
  event_id bigint not null references events on delete cascade,
  sender_id uuid not null references profiles on delete cascade,
  body text not null check (length(trim(body)) between 1 and 1000),
  created_at timestamptz not null default now()
);
create index event_messages_event on event_messages (event_id, created_at);

create table event_reviews (
  event_id bigint not null references events on delete cascade,
  user_id uuid not null references profiles on delete cascade,
  stars int not null check (stars between 1 and 5),
  body text not null default '',
  created_at timestamptz not null default now(),
  primary key (event_id, user_id)
);

-- „Wiedersehen“-Wünsche bleiben verborgen; gegenseitige werden zu Matches.
create table event_wishes (
  event_id bigint not null references events on delete cascade,
  from_id uuid not null references profiles on delete cascade,
  to_id uuid not null references profiles on delete cascade,
  primary key (event_id, from_id, to_id),
  check (from_id <> to_id)
);

alter table events enable row level security;
alter table event_attendees enable row level security;
alter table event_invites enable row level security;
alter table event_messages enable row level security;
alter table event_reviews enable row level security;
alter table event_wishes enable row level security;
revoke all on events, event_attendees, event_invites, event_messages, event_reviews, event_wishes from anon, authenticated;

-- Ein Event gilt 3 Stunden nach Beginn als vorbei; danach kommt der Rückblick.
create function event_over(e events) returns boolean
language sql stable as $$ select e.starts_at + interval '3 hours' < now() $$;

-- „Heute, 21:00 Uhr“, „Morgen, 12:30 Uhr“ oder „Samstag, 14:00 Uhr“ (deutsche Zeit).
create function event_when_label(ts timestamptz) returns text
language sql stable as $$
  select case (ts at time zone 'Europe/Berlin')::date - (now() at time zone 'Europe/Berlin')::date
           when 0 then 'Heute' when 1 then 'Morgen'
           else (array['Sonntag', 'Montag', 'Dienstag', 'Mittwoch', 'Donnerstag', 'Freitag', 'Samstag'])
                  [extract(dow from ts at time zone 'Europe/Berlin')::int + 1]
         end || ', ' || to_char(ts at time zone 'Europe/Berlin', 'HH24:MI') || ' Uhr'
$$;

-- Das Event, wenn ich es sehen darf: eigenes Gebiet und niemand hat den anderen blockiert.
create function event_for_me(p_event bigint) returns events
language plpgsql stable security definer set search_path = public as $$
declare e events;
begin
  select ev.* into e from events ev join profiles me on me.id = auth.uid()
  where ev.id = p_event and ev.area_id = me.area_id and me.status = 'admitted'
    and not blocked_between(auth.uid(), ev.host_id);
  if e.id is null then raise exception 'no event' using errcode = 'insufficient_privilege'; end if;
  return e;
end $$;

create function event_people(p_event bigint) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('id', p.id, 'name', p.display_name,
           'age', date_part('year', age(p.birthdate))::int, 'gender', a.gender) order by a.joined_at), '[]')
  from event_attendees a join profiles p on p.id = a.user_id
  where a.event_id = p_event and a.user_id <> auth.uid()
$$;

create function event_host(p_host uuid) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'name', (select display_name from profiles where id = p_host),
    'events', (select count(*) from events e where e.host_id = p_host and event_over(e)),
    'ratings', (select coalesce(jsonb_agg(r.stars), '[]') from event_reviews r join events e on e.id = r.event_id
                where e.host_id = p_host and r.user_id <> p_host),
    'reviews', (select coalesce(jsonb_agg(body order by created_at desc), '[]') from (
                  select r.body, r.created_at from event_reviews r join events e on e.id = r.event_id
                  where e.host_id = p_host and r.user_id <> p_host and r.body <> ''
                  order by r.created_at desc limit 3) x))
$$;

