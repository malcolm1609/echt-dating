create function create_event(title text, kind text, place text, when_text text, starts_at timestamptz, seats int,
                             price numeric, access text, campus text, tonight boolean, invitees uuid[]) returns text
language plpgsql security definer set search_path = public as $$
declare
  me profiles;
  new_id bigint;
begin
  select * into me from profiles where id = auth.uid() and status = 'admitted';
  if me.id is null then raise exception 'not admitted' using errcode = 'insufficient_privilege'; end if;
  if starts_at < now() - interval '1 hour' or starts_at > now() + interval '60 days' then
    raise exception 'bad time' using errcode = 'check_violation';
  end if;
  insert into events (host_id, area_id, title, kind, place, when_text, starts_at, seats, price, access, campus, tonight)
    values (me.id, me.area_id, trim(title), kind, trim(place), when_text, starts_at, seats, price, access, campus, tonight)
    returning id into new_id;
  insert into event_attendees (event_id, user_id, gender) values (new_id, me.id, me.gender);
  -- Einladen kann man nur eigene Matches.
  insert into event_invites (event_id, user_id)
    select new_id, u from unnest(coalesce(invitees, '{}')) u
    where exists (select from matches where user_a = least(me.id, u) and user_b = greatest(me.id, u))
      and not blocked_between(me.id, u)
    on conflict do nothing;
  return new_id::text;
end $$;

-- Ein Platz in der eigenen Hälfte; die Sperre auf dem Event verhindert, dass zwei gleichzeitig den letzten nehmen.
create function join_event(event_id text) returns void
language plpgsql security definer set search_path = public as $$
declare
  e events := event_for_me(event_id::bigint);
  g text := (select gender from profiles where id = auth.uid());
begin
  perform from events where id = e.id for update;
  if event_over(e) then raise exception 'event over' using errcode = 'check_violation'; end if;
  if exists (select from event_attendees a where a.event_id = e.id and a.user_id = auth.uid()) then return; end if;
  if e.access = 'invite' and not exists (select from event_invites i where i.event_id = e.id and i.user_id = auth.uid()) then
    raise exception 'invite only' using errcode = 'insufficient_privilege';
  end if;
  if (select count(*) from event_attendees a where a.event_id = e.id and a.gender = g) >= e.seats / 2 then
    raise exception 'full' using errcode = 'check_violation';
  end if;
  insert into event_attendees (event_id, user_id, gender) values (e.id, auth.uid(), g);
end $$;

-- Der Gastgeber bleibt dabei; alle anderen können absagen, solange das Event nicht vorbei ist.
create function leave_event(event_id text) returns void
language plpgsql security definer set search_path = public as $$
declare e events := event_for_me(event_id::bigint);
begin
  if e.host_id = auth.uid() then raise exception 'host stays' using errcode = 'check_violation'; end if;
  delete from event_attendees a where a.event_id = e.id and a.user_id = auth.uid() and not event_over(e);
end $$;

create function send_event_message(event_id text, body text) returns void
language plpgsql security definer set search_path = public as $$
declare e events := event_for_me(event_id::bigint);
begin
  if not exists (select from event_attendees a where a.event_id = e.id and a.user_id = auth.uid()) then
    raise exception 'not attending' using errcode = 'insufficient_privilege';
  end if;
  insert into event_messages (event_id, sender_id, body) values (e.id, auth.uid(), trim(body));
  -- Testbetrieb: Gastgeber aus den Beispielprofilen antworten einmal.
  if beta_bot(e.host_id) and not exists (select from event_messages m where m.event_id = e.id and m.sender_id = e.host_id) then
    insert into event_messages (event_id, sender_id, body, created_at)
      values (e.id, e.host_id, 'Schön, dass du dabei bist! Ich warte am Treffpunkt, ihr erkennt mich an der roten Jacke 🙂', now() + interval '1 second');
  end if;
end $$;

-- Sterne, ein Satz und Wiedersehen-Wünsche, einmal pro Event. Gibt die gegenseitigen Wünsche zurück;
-- daraus werden Matches (mit Fragenrunde wie nach einem Like).
create function review_event(event_id text, stars int, body text, picks uuid[]) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  e events;
  mutual uuid[];
  u uuid;
begin
  select * into e from events where id = event_id::bigint;
  if e.id is null or not exists (select from event_attendees a where a.event_id = e.id and a.user_id = auth.uid()) then
    raise exception 'not attending' using errcode = 'insufficient_privilege';
  end if;
  if not event_over(e) then raise exception 'event not over' using errcode = 'check_violation'; end if;
  insert into event_reviews (event_id, user_id, stars, body) values (e.id, auth.uid(), stars, trim(coalesce(body, '')));
  insert into event_wishes (event_id, from_id, to_id)
    select e.id, auth.uid(), p from unnest(coalesce(picks, '{}')) p
    where exists (select from event_attendees a where a.event_id = e.id and a.user_id = p)
    on conflict do nothing;
  select coalesce(array_agg(w.to_id), '{}') into mutual from event_wishes w
  where w.event_id = e.id and w.from_id = auth.uid()
    and exists (select from event_wishes back where back.event_id = e.id and back.from_id = w.to_id and back.to_id = auth.uid())
    and not blocked_between(auth.uid(), w.to_id);
  foreach u in array mutual loop
    insert into matches (user_a, user_b) values (least(auth.uid(), u), greatest(auth.uid(), u)) on conflict do nothing;
  end loop;
  return to_jsonb(mutual);
end $$;

