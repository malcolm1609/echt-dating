-- Events der Beispielprofile neu anlegen: einer für heute Abend, drei in den nächsten Tagen und ein
-- vergangener Brettspielabend mit der Testperson, bei dem zwei sie wiedersehen möchten.
create function beta_prepare_events(tester uuid) returns void
language plpgsql security definer set search_path = public as $$
declare
  me profiles;
  same uuid[];
  other uuid[];
  host_f uuid;
  host_m uuid;
  tonight_at timestamptz := date_trunc('hour', now()) + interval '3 hours';
  tomorrow date := (now() at time zone 'Europe/Berlin')::date + 1;
  past_id bigint;
  ev bigint;
begin
  if not beta_enabled() then raise exception 'beta disabled' using errcode = 'insufficient_privilege'; end if;
  select * into me from profiles where id = tester;
  -- Kommende Events der Beispielprofile gelten für alle, vergangene nur für die jeweilige Testperson.
  delete from events e where e.host_id in (select id from profiles where is_sample)
    and (not event_over(e) or exists (select from event_attendees a where a.event_id = e.id and a.user_id = tester));
  select array_agg(id order by display_name) into same from profiles where is_sample and gender = me.gender and area_id = me.area_id;
  select array_agg(id order by display_name) into other from profiles where is_sample and gender <> me.gender and area_id = me.area_id;
  if coalesce(array_length(same, 1), 0) < 4 or coalesce(array_length(other, 1), 0) < 6 then return; end if;
  host_f := case when me.gender = 'f' then same[1] else other[1] end;
  host_m := case when me.gender = 'm' then same[1] else other[1] end;

  insert into events (host_id, area_id, title, kind, place, when_text, starts_at, seats, tonight)
    values (host_f, me.area_id, 'Kneipentour, wer kommt mit?', 'Feiern', 'Start an der Bar am Seltersweg',
            event_when_label(tonight_at), tonight_at, 8, true) returning id into ev;
  insert into event_attendees (event_id, user_id, gender) select ev, id, gender from profiles
    where id in (host_f, other[2], same[2]) on conflict do nothing;

  insert into events (host_id, area_id, title, kind, place, when_text, starts_at, seats)
    values (host_m, me.area_id, 'Pub-Quiz mit Fremden', 'Spiele', 'Irish Pub am Kirchenplatz',
            event_when_label((tomorrow + time '19:30') at time zone 'Europe/Berlin'), (tomorrow + time '19:30') at time zone 'Europe/Berlin', 12)
    returning id into ev;
  insert into event_attendees (event_id, user_id, gender) select ev, id, gender from profiles
    where id in (host_m, other[3], other[4], same[3]) on conflict do nothing;

  insert into events (host_id, area_id, title, kind, place, when_text, starts_at, seats, campus)
    values (host_f, me.area_id, 'Mittag in der Mensa mit Fremden', 'Essen & Trinken', 'Mensa Otto-Behaghel-Straße, Tisch mit Echt-Schild',
            event_when_label((tomorrow + time '12:30') at time zone 'Europe/Berlin'), (tomorrow + time '12:30') at time zone 'Europe/Berlin', 8, 'JLU Gießen')
    returning id into ev;
  insert into event_attendees (event_id, user_id, gender) select ev, id, gender from profiles
    where id in (host_f, other[5]) on conflict do nothing;

  insert into events (host_id, area_id, title, kind, place, when_text, starts_at, seats, price)
    values (host_m, me.area_id, 'Bouldern für Anfänger', 'Sport', 'Boulderhalle in der Weststadt',
            event_when_label((tomorrow + 2 + time '14:00') at time zone 'Europe/Berlin'), (tomorrow + 2 + time '14:00') at time zone 'Europe/Berlin', 8, 12)
    returning id into ev;
  insert into event_attendees (event_id, user_id, gender) select ev, id, gender from profiles
    where id in (host_m, same[4]) on conflict do nothing;

  insert into events (host_id, area_id, title, kind, place, when_text, starts_at, seats, created_at)
    values (host_m, me.area_id, 'Brettspielabend', 'Spiele', 'Spielecafé in der Innenstadt', 'Vorgestern, 19:00 Uhr',
            now() - interval '2 days', 10, now() - interval '5 days')
    returning id into past_id;
  insert into event_attendees (event_id, user_id, gender) select past_id, id, gender from profiles
    where id in (tester, host_m, same[2], same[3], other[2], other[3], other[4]) on conflict do nothing;
  insert into event_wishes (event_id, from_id, to_id) values (past_id, other[2], tester), (past_id, other[3], tester);
  insert into event_reviews (event_id, user_id, stars, body) values
    (past_id, other[4], 5, 'Lockere Runde, alle wurden gut eingebunden.'),
    (past_id, same[2], 4, 'Schwere Fragen, aber super Stimmung.');
end $$;

create or replace function beta_reset_me() returns void
language plpgsql security definer set search_path = public as $$
begin
  if not beta_enabled() then raise exception 'beta disabled' using errcode = 'insufficient_privilege'; end if;
  delete from blocks where (blocker_id = auth.uid() and blocked_id in (select id from profiles where is_sample))
                        or (blocked_id = auth.uid() and blocker_id in (select id from profiles where is_sample));
  delete from reports where reporter_id = auth.uid() and reported_id in (select id from profiles where is_sample);
  delete from events where host_id = auth.uid();
  perform beta_prepare_tester(auth.uid());
  perform beta_prepare_events(auth.uid());
end $$;

