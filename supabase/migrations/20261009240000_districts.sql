-- Gebiete sind Landkreise und kreisfreie Städte (Malcolm, 2026-10-09). Zulassung und Geschlechterbalance gelten im
-- Landkreis, in dem man wohnt; die Vorschläge richten sich weiter nur nach dem eigenen Umkreis. Die Grenzen lädt
-- scripts/load-districts.mjs (BKG, © GeoBasis-DE / BKG, dl-de/by-2-0) über load_districts().
-- Gebiete ohne Umriss (z. B. aus Lasttests oder bevor die Grenzen geladen sind) gelten weiter per Radius.

alter table areas add column code text unique;

create table area_shapes (
  id bigint generated by default as identity primary key,
  area_id bigint not null references areas on delete cascade,
  shape polygon not null,
  size double precision not null
);
create index area_shapes_area on area_shapes (area_id);
create index area_shapes_shape on area_shapes using gist (shape);
alter table area_shapes enable row level security;
revoke all on area_shapes from anon, authenticated;

